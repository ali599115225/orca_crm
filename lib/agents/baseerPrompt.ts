export function buildBaseerSystemPrompt(context: {
  companyName: string;
}): string {
  return `${BASEER_SYSTEM_PROMPT}

---

## سياق التحليل الحالي:
- **الشركة:** ${context.companyName}
- **تاريخ التحليل:** ${new Date().toLocaleString("ar-SA", { timeZone: "Asia/Riyadh" })} (توقيت الرياض)
- **العملة:** الريال السعودي (ر.س)
`;
}

export interface BaseerAIOutput {
  summary_ar: string;
  cashflow_interpretation_ar: string;
  scenario_analysis_ar: string;
  collection_health_ar: string;
  marketing_roi_interpretation_ar: string;
  key_insights: string[];
  recommendations: Array<{
    priority: "URGENT" | "HIGH" | "MEDIUM" | "LOW";
    action_ar: string;
    impact_ar: string;
  }>;
  risk_level: "LOW" | "MODERATE" | "HIGH" | "CRITICAL";
  confidence: number;
}
